def _redis_reachable(url):
    try:
        import redis  # noqa: F401
    except ImportError:
        return False
    parts = urlparse(url)
    try:
        with socket.create_connection(
            (parts.hostname or '127.0.0.1', parts.port or 6379), timeout=0.5,
        ):
            return True
    except OSError:
        return False


# Answer cache: Redis when reachable, per-process in-memory otherwise.
